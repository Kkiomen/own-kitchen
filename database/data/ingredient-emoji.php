 *   "Coś zupełnie osobliwego" in Soups; here it would make "makrela" into flour.
 * - A trailing `*` opts into prefix matching, for the stems Polish declension
 *   needs (`pomidor*` covers pomidora, pomidorami, pomidorowy).
 * - **The longest matching needle wins**, so a specific entry can override a
